class Dense(Layer):
    def __init__(self, name: str = "Dense", mode: str = "train") -> None:
        super().__init__(name, {"X", "W", "b"}, mode)

    def _forward(
        self,
        X: np.ndarray[np.float64],
        W: np.ndarray[np.float64],
        b: np.ndarray[np.float64],
    ) -> np.ndarray[np.float64]:
        return X @ W + b

    def _backward(
        self, grad: np.ndarray[np.float64]
    ) -> dict[str, np.ndarray[np.float64]]:
        return {
            "X": grad @ self.input["W"].T,
            "W": self.input["X"].T @ grad,
            "b": np.sum(grad, axis=0),
        }


class L2Loss(Layer):
    def __init__(self, name: str = "MeanSquaredError", mode: str = "train") -> None:
        super().__init__(name, {"y_pred", "y_true"}, mode)

    def _forward(
        self,
        y_pred: np.ndarray[np.float64],
        y_true: np.ndarray[np.float64],
    ) -> np.ndarray[np.float64]:
        return np.array(np.mean((y_pred - y_true) ** 2), dtype=np.float64)

    def _backward(
        self, grad: np.ndarray[np.float64]
    ) -> dict[str, np.ndarray[np.float64]]:
        err = self.input["y_pred"] - self.input["y_true"]
        return {
            "y_pred": 2 * grad * err / len(self.input["y_true"]),
            "y_true": np.zeros_like(self.input["y_true"], dtype=np.float64),
        }


class CrossEntropyLoss(Layer):
    """
    Onion requires all values to be floating-point, so inputs to this layer
    must already be one-hot encoded.
    """

    def __init__(self, name: str = "CrossEntropyLoss", mode: str = "train") -> None:
        super().__init__(name, {"y_pred", "y_true"}, mode)

    def _forward(
        self,
        y_pred: np.ndarray[np.float64],
        y_true: np.ndarray[np.float64],
    ) -> np.ndarray[np.float64]:
        err = np.sum(softmax(y_pred) * y_true, axis=-1)
        return -np.mean(np.log(err), axis=-1)

    def _backward(
        self, grad: np.ndarray[np.float64]
    ) -> dict[str, np.ndarray[np.float64]]:
        return {
            "y_pred": grad
            * (softmax(self.input["y_pred"]) - self.input["y_true"])
            / len(self.input["y_true"]),
            "y_true": np.zeros_like(self.input["y_true"], dtype=np.float64),
        }


class L2Regularization(Layer):
    def __init__(
        self, name: str = "L2Reg", reg: float = 0.01, mode: str = "train"
    ) -> None:
        super().__init__(name, {"W"}, mode)
        self.reg = reg

    def _forward(
        self,
        W: np.ndarray[np.float64],
    ) -> np.ndarray[np.float64]:
        return self.reg * np.sum(W**2) if self.is_train() else 0.0

    def _backward(
        self, grad: np.ndarray[np.float64]
    ) -> dict[str, np.ndarray[np.float64]]:
        return {
            "W": 2 * self.reg * grad * self.input["W"] if self.is_train() else 0.0,
        }

    def to_config(self) -> dict[str, object]:
        return {"reg": self.reg}

    @classmethod
    def from_config(cls, name: str, cfg: dict[str, object]) -> typing.Self:
        return L2Regularization(name=name, reg=cfg["reg"])


class BatchNorm(Layer):
    def __init__(
        self,
        name: str = "BatchNorm",
        axis: int | tuple[int] = 0,
        momentum: float = 0.1,
        eps: float = 1e-8,
        mode: str = "train",
    ) -> None:
        super().__init__(name, {"a", "gamma", "beta"}, mode)
        self.axis = axis
        self.mtm = momentum
        self.cache = None
        self.amean, self.avar = 0, 1
        self.eps = eps

    def _forward(
        self,
        a: np.ndarray[np.float64],
        gamma: np.ndarray[np.float64],
        beta: np.ndarray[np.float64],
    ) -> np.ndarray[np.float64]:
        if self.is_train():
            mean = np.mean(a, axis=self.axis)
            var = np.var(a, axis=self.axis) + self.eps
            irtvar = var**-0.5
            xhat = (a - mean) * irtvar
            self.cache = irtvar, xhat
            
            self.amean = self.amean * (1 - self.mtm) + mean * self.mtm
            self.avar = self.avar * (1 - self.mtm) + var * self.mtm

            return gamma * xhat + beta

        return gamma * (a - self.amean) / np.sqrt(self.avar) + beta

    def _backward(
        self, grad: np.ndarray[np.float64]
    ) -> dict[str, np.ndarray[np.float64]]:
        irtvar, xhat = self.cache
        dxh = grad * self.input["gamma"]
        return {
            "a": dxh - xhat * np.mean(dxh * xhat, axis=self.axis) - np.mean(dxh, axis=self.axis) * irtvar,
            "gamma": np.sum(grad * xhat, axis=self.axis),
            "beta": np.sum(grad, axis=self.axis),
        }

    def to_config(self) -> dict[str, object]:
        return {
            "axis": self.axis,
            "mean": self.amean,
            "var": self.avar,
            "mtm": self.mtm,
            "eps": self.eps,
        }

    @classmethod
    def from_config(cls, name: str, cfg: dict[str, object]) -> typing.Self:
        layer = BatchNorm(
            name=name, axis=cfg["axis"], momentum=cfg["mtm"], eps=cfg["eps"]
        )
        layer.amean, layer.avar = cfg["mean"], cfg["var"]
        return layer


class Dropout(Layer):
    def __init__(
        self, name: str = "Dropout", p: float = 0.5, mode: str = "train"
    ) -> None:
        super().__init__(name, {"a"}, mode)
        self.p = p
        self.mask = None

    def _forward(
        self,
        a: np.ndarray[np.float64],
    ) -> np.ndarray[np.float64]:
        if self.is_train():
            self.mask = np.random.random((1, *a.shape[1:])) > self.p
            return a * self.mask / (1 - self.p)
        return a

    def _backward(
        self, grad: np.ndarray[np.float64]
    ) -> dict[str, np.ndarray[np.float64]]:
        if self.is_train():
            return {"a": grad * self.mask / (1 - self.p)}
        return {"a": grad}

    def to_config(self) -> dict[str, object]:
        return {"p": self.p}

    @classmethod
    def from_config(cls, name: str, cfg: dict[str, object]) -> typing.Self:
        return Dropout(name=name, p=cfg["p"])

