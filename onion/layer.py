import typing
import numpy as np

from onion.util import softmax, tr_, stride_slices, pad_arr, grid

class Layer:
    """
    Layers are the core component of any model.
    Each layer takes in multiple named inputs, and returns a single output.
    A layer can either be in train mode or eval mode.
    This affects certain layers like batch norm, dropout, and regularization.
    """
    def __init__(
        self,
        name: str = "Layer",
        inputs: set[str] | None = None,
        mode: str = "train",
    ) -> None:
        self.name = name
        self.input_names = inputs if inputs is not None else set()

        self.mode = mode

        self.input: dict[str, np.ndarray[np.float64]] | None = None
        self.output: np.ndarray[np.float64] | None = None
        self.input_grad: dict[str, np.ndarray[np.float64]] | None = None
        self.output_grad: np.ndarray[np.float64] | None = None

    def train(self) -> None:
        self.mode = "train"

    def eval(self) -> None:
        self.mode = "eval"

    def is_train(self) -> bool:
        return self.mode == "train"

    def is_eval(self) -> bool:
        return self.mode == "eval"

    @property
    def params(self) -> dict[str, np.ndarray[np.float64]]:
        pass

    def _forward(self, **inputs: np.ndarray[np.float64]) -> np.ndarray[np.float64]:
        raise NotImplementedError

    def _backward(
        self, grad: np.ndarray[np.float64]
    ) -> dict[str, np.ndarray[np.float64]]:
        raise NotImplementedError

    def forward(self, **inputs: np.ndarray[np.float64]) -> np.ndarray[np.float64]:
        assert set(inputs) == self.input_names
        inputs = {
            name: inp.forward() if isinstance(inp, Layer) else inp
            for name, inp in inputs.items()
        }
        if self.is_train():
            self.input, self.output = inputs, self._forward(**inputs)
            return self.output
        return self._forward(**inputs)

    def backward(
        self, grad: np.ndarray[np.float64] | None = None
    ) -> dict[str, np.ndarray[np.float64]]:
        assert self.input is not None
        assert self.is_train(), "Layer must be in training mode for backward pass!"
        if grad is None:
            grad = np.ones_like(self.output)

        assert grad.shape == self.output.shape

        self.output_grad, self.input_grad = grad, self._backward(grad)

        for name in self.input_names:
            assert self.input_grad[name].shape == self.input[name].shape, (
                name,
                self.input_grad[name].shape,
                self.input[name].shape,
            )
        return self.input_grad

    def __str__(self) -> str:
        return f"Layer {self.name}"

    def to_config(self) -> dict[str, object]:
        return {}

    @classmethod
    def from_config(cls, name: str, cfg: dict[str, object]) -> typing.Self:
        return cls(name=name)

    @classmethod
    def all_subclasses(cls) -> dict[str, type]:
        result = {}
        stack = [cls]
        while stack:
            c = stack.pop()
            for subclass in c.__subclasses__():
                if subclass not in result:
                    result[str(subclass)[8:-2]] = subclass
                    stack.append(subclass)
        return result

    def grad_check(self, eps: float = 1e-5, **inputs: np.ndarray[np.float64]) -> None:
        self.forward(**inputs)
        self.backward(np.random.standard_normal(self.output.shape).astype(np.float64))
        grad = self.input_grad
        worst_err = 0
        for name in inputs:
            print(f"Checking {name}:")
            # print(f"Analytical gradient {grad[name]}")
            numgrad = np.zeros(inputs[name].shape, dtype=np.float64)
            for i, val in np.ndenumerate(inputs[name]):
                inputs[name][i] = val + eps
                out1 = self.forward(**inputs)
                inputs[name][i] = val - eps
                out2 = self.forward(**inputs)
                inputs[name][i] = val
                numgrad[i] = np.sum((out1 - out2) * self.output_grad) / (2 * eps)
            # print(f"Numerical gradient {numgrad}")
            err = abs(numgrad - grad[name])
            print(f"Difference {err}")
            worst_err = max(worst_err, np.max(err, axis=None))
            print()
        print("worst error:", worst_err)


class Parameter(Layer):
    """
    Parameters are special layers with memory,
    storing trainable parameters for adjustment by the optimizer.
    A parameter can be specified by a shape or a starting value.
    If a shape is provided, the parameter is generated by a normal distribution
    with a standard deviation provided by the scale parameter.
    """

    def __init__(
        self,
        name: str = "Param",
        value: int | tuple[int] | np.ndarray[np.float64] | None = None,
        shift: float = 0.0,
        scale: float = 1.0,
        mode: str = "train",
    ) -> None:
        super().__init__(name, mode=mode)

        if isinstance(value, int):
            value = (value,)
        if not isinstance(value, np.ndarray):
            value = shift + np.random.standard_normal(value) * scale

        self.value = value
        self.shape = self.value.shape

    def _forward(self) -> np.ndarray[np.float64]:
        return self.value

    def _backward(
        self, grad: np.ndarray[np.float64] | None = None
    ) -> dict[str, np.ndarray[np.float64]]:
        return {}

    def __str__(self) -> str:
        return f"Parameter {self.name}, shape {self.shape}"

    def to_config(self) -> dict[str, object]:
        return {"value": self.value}

    @classmethod
    def from_config(cls, name: str, cfg: dict[str, object]) -> typing.Self:
        return Parameter(name=name, value=cfg["value"])


class ReLU(Layer):
    def __init__(self, name: str = "ReLU", mode: str = "train") -> None:
        super().__init__(name, {"a"}, mode)

    def _forward(self, a: np.ndarray[np.float64]) -> np.ndarray[np.float64]:
        return np.maximum(a, 0)

    def _backward(
        self, grad: np.ndarray[np.float64]
    ) -> dict[str, np.ndarray[np.float64]]:
        return {"a": grad * (self.input["a"] > 0)}


class Sigmoid(Layer):
    def __init__(self, name: str = "Sigmoid", mode: str = "train") -> None:
        super().__init__(name, {"a"}, mode)

    def _forward(self, a: np.ndarray[np.float64]) -> np.ndarray[np.float64]:
        return np.tanh(a)

    def _backward(
        self, grad: np.ndarray[np.float64]
    ) -> dict[str, np.ndarray[np.float64]]:
        return {"a": grad * (1 - self.output**2)}


